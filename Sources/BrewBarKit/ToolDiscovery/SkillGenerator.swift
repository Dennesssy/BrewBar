import Foundation

/// Renders `ToolDocumentation` to Agent Skills (`SKILL.md`) under `skillsRoot`.
public struct SkillGenerator: SkillWriting {
    public let skillsRoot: URL

    public init(skillsRoot: URL = BrewBarPaths.skills) {
        self.skillsRoot = skillsRoot
    }

    static let maxDescriptionLength = 200
    static let maxOptionRows = 80

    public static func render(_ doc: ToolDocumentation) -> String {
        let tool = doc.tool
        let name = tool.name
        var out = ""

        out += "---\n"
        out += "name: \(yamlName(name))\n"
        out += "description: \"\(yamlEscape(description(for: doc)))\"\n"
        out += "---\n\n"

        out += "# \(name)\n\n"
        out += "\(collapse(doc.tree.summary) ?? collapse(tool.summary) ?? "Installed command-line tool.")\n\n"
        out += "Installed at `\(tool.path)` · formula `\(tool.formula)` \(tool.version) · docs from \(sourceLabel(doc.source))\n"

        let usage = doc.tree.usage.compactMap { collapse($0) }
        if !usage.isEmpty {
            let body = usage.joined(separator: "\n")
            let fence = fence(for: body)
            out += "\n## Usage\n\(fence)\n\(body)\n\(fence)\n"
        }

        let options = doc.tree.options
        if !options.isEmpty {
            out += "\n## Options\n"
            out += "| Flag | Argument | Description |\n"
            out += "|---|---|---|\n"
            for option in options.prefix(maxOptionRows) {
                let flags = option.flags.map { "`\(escapeCell($0))`" }.joined(separator: ", ")
                let argument = option.argument.map { "`\(escapeCell($0))`" } ?? ""
                out += "| \(flags) | \(argument) | \(escapeCell(option.summary)) |\n"
            }
            let hidden = options.count - maxOptionRows
            if hidden > 0 {
                out += "\n_…\(hidden) more options — see full reference._\n"
            }
        }

        let subcommands = doc.tree.subcommands
        if !subcommands.isEmpty {
            out += "\n## Subcommands\n"
            for sub in subcommands {
                out += bullet(for: sub, indent: "")
                for nested in sub.subcommands {
                    out += bullet(for: nested, indent: "  ")
                }
            }
        }

        out += "\n## Full reference\n"
        out += "Run `man \(name)` or `\(name) --help`, or call the brewbar MCP tool `get_man_page` with tool \"\(name)\".\n"
        return out
    }

    public func writeSkill(for doc: ToolDocumentation) async throws -> URL {
        let name = doc.tool.name
        guard BrewBarPaths.isSafeComponent(name) else {
            throw ToolDiscoveryError.invalidToolName(name)
        }
        let root = skillsRoot.standardizedFileURL
        let dir = root.appendingPathComponent(name, isDirectory: true).standardizedFileURL
        var rootPrefix = root.path
        if !rootPrefix.hasSuffix("/") { rootPrefix += "/" }
        guard dir.path.hasPrefix(rootPrefix) else {
            throw ToolDiscoveryError.invalidToolName(name)
        }

        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        let file = dir.appendingPathComponent("SKILL.md")
        try Data(Self.render(doc).utf8).write(to: file, options: .atomic)
        return file
    }

    /// Writes `<skillsRoot>/README.md`, an index linking each tool's SKILL.md.
    public func writeIndex(tools: [InstalledTool]) throws -> URL {
        try FileManager.default.createDirectory(at: skillsRoot, withIntermediateDirectories: true)
        var out = "# BrewBar skills\n\n"
        out += "Generated by BrewBar from installed Homebrew command-line tools. Each entry links to its SKILL.md.\n\n"
        let safe = tools.filter { BrewBarPaths.isSafeComponent($0.name) }
        for tool in safe.sorted(by: { $0.name < $1.name }) {
            let summary = Self.collapse(tool.summary) ?? "installed command-line tool"
            out += "- [\(tool.name)](\(tool.name)/SKILL.md) — \(summary) (\(tool.formula))\n"
        }
        let file = skillsRoot.appendingPathComponent("README.md")
        try Data(out.utf8).write(to: file, options: .atomic)
        return file
    }

    // MARK: - Helpers

    private static func description(for doc: ToolDocumentation) -> String {
        let name = doc.tool.name
        let prefix = "Use the `\(name)` CLI (Homebrew formula \(doc.tool.formula) \(doc.tool.version)) — "
        let suffix = ". Load before composing \(name) commands."
        let summary = collapse(doc.tree.summary) ?? collapse(doc.tool.summary) ?? "installed command-line tool"
        let budget = max(0, maxDescriptionLength - prefix.count - suffix.count)
        let line = prefix + truncate(summary, to: budget) + suffix
        return String(line.prefix(maxDescriptionLength))
    }

    private static func bullet(for node: CommandNode, indent: String) -> String {
        let summary = collapse(node.summary).map { " — \($0)" } ?? ""
        return "\(indent)- `\(escapeCell(node.name))`\(summary)\n"
    }

    private static func sourceLabel(_ source: ToolDocSource) -> String {
        switch source {
        case .manPage: "man page"
        case .helpFlag: "`--help`"
        case .none: "none"
        }
    }

    /// Plain YAML scalar when unambiguous, otherwise double-quoted.
    private static func yamlName(_ name: String) -> String {
        let reserved: Set<String> = ["true", "false", "yes", "no", "on", "off", "null"]
        let plain = name.first.map { $0.isASCII && $0.isLetter } == true
            && name.allSatisfy { $0.isASCII && ($0.isLetter || $0.isNumber || "-_.".contains($0)) }
            && !reserved.contains(name.lowercased())
        return plain ? name : "\"\(yamlEscape(name))\""
    }

    private static func yamlEscape(_ text: String) -> String {
        text.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"")
    }

    /// Single-line form of `text`: whitespace and control characters collapse to one space.
    private static func collapse(_ text: String?) -> String? {
        guard let text else { return nil }
        let parts = text.split { ch in
            ch.isWhitespace || ch.isNewline || ch.unicodeScalars.first?.properties.generalCategory == .control
        }
        let joined = parts.joined(separator: " ")
        return joined.isEmpty ? nil : joined
    }

    private static func escapeCell(_ text: String) -> String {
        (collapse(text) ?? "").replacingOccurrences(of: "|", with: "\\|")
    }

    private static func truncate(_ text: String, to limit: Int) -> String {
        guard text.count > limit else { return text }
        guard limit > 0 else { return "" }
        return String(text.prefix(limit - 1)) + "…"
    }

    /// Code fence longer than any backtick run in `body`.
    private static func fence(for body: String) -> String {
        var longest = 0
        var run = 0
        for ch in body {
            run = ch == "`" ? run + 1 : 0
            longest = max(longest, run)
        }
        return String(repeating: "`", count: max(3, longest + 1))
    }
}
